<#
.SYNOPSIS
    Create the Android release signing key and its Gradle properties file.

.DESCRIPTION
    Android refuses to install an unsigned APK, so a release build needs a key.
    This generates one with keytool and writes keystore.properties next to the
    generated Android project.

    Both outputs are gitignored. Back the .jks file up: losing it means future
    builds cannot upgrade an installed copy, only replace it.

.PARAMETER Password
    Keystore and key password. Generated when omitted.
#>
[CmdletBinding()]
param(
    [string]$Password
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$android = Join-Path $root 'src-tauri\gen\android'
$keystore = Join-Path $android 'shadow720-release.jks'
$properties = Join-Path $android 'keystore.properties'

if (Test-Path $keystore) {
    throw "A keystore already exists at $keystore. Delete it deliberately if you mean to replace it."
}

if (-not $Password) {
    # 24 random bytes, base64url, so the value is safe inside a properties file.
    $bytes = New-Object byte[] 24
    [System.Security.Cryptography.RandomNumberGenerator]::Fill($bytes)
    $Password = [Convert]::ToBase64String($bytes).Replace('+', '-').Replace('/', '_').TrimEnd('=')
}

$keytool = if ($env:JAVA_HOME) { Join-Path $env:JAVA_HOME 'bin\keytool.exe' } else { 'keytool' }

& $keytool -genkeypair `
    -keystore $keystore `
    -alias shadow720 `
    -keyalg RSA -keysize 4096 -validity 10000 `
    -storepass $Password -keypass $Password `
    -dname 'CN=Shadow720, OU=Release, O=Shadow720, L=Unknown, ST=Unknown, C=US'

if ($LASTEXITCODE -ne 0) { throw "keytool failed with exit code $LASTEXITCODE" }

@"
# Generated by scripts/new-android-keystore.ps1. Gitignored: never commit this.
storeFile=shadow720-release.jks
storePassword=$Password
keyAlias=shadow720
keyPassword=$Password
"@ | Set-Content -Path $properties -Encoding utf8

Write-Host "Keystore:   $keystore" -ForegroundColor Green
Write-Host "Properties: $properties" -ForegroundColor Green
Write-Host "`nBack up the .jks file and the password. Losing them means you cannot" -ForegroundColor Yellow
Write-Host "ship an update that upgrades an existing install." -ForegroundColor Yellow
