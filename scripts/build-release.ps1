<#
.SYNOPSIS
    Build the Play Store bundle and the downloadable Windows packages into release/.

.DESCRIPTION
    Produces the artifacts that are actually shipped:

      * Windows  - NSIS installer and MSI, via `tauri build`
      * Android  - signed arm64 AAB for Google Play, and a signed arm64 APK

    Google Play requires an Android App Bundle (.aab) for new apps and for any
    update that changes the signing key. The APK is produced alongside it on every
    run because it is what a tester sideloads and what a user installs outside
    Play; shipping a release without one leaves those users with nothing to
    install. Both are signed with the same key, so an APK and an AAB from one run
    are interchangeable for the same versionCode.

    The bundle must be signed or Play rejects the upload. The signing key is read
    from src-tauri/gen/android/keystore.properties, which is gitignored; see
    scripts/new-android-keystore.ps1 to create one.

    The version is read from tauri.conf.json and written into the gitignored
    app/tauri.properties before Gradle runs. Building through Gradle directly
    bypasses the Tauri CLI, which is what normally writes that file, so without
    this step the bundle silently ships a stale versionCode and Play rejects it as
    a duplicate.

.PARAMETER SkipWindows
    Build only the Android artifacts.

.PARAMETER SkipAndroid
    Build only the Windows installers.

.PARAMETER ApkOnly
    Build only the sideloadable APK, skipping the Play bundle. Useful for a quick
    device test; a release run should not use this, because Play needs the .aab.
#>
[CmdletBinding()]
param(
    [switch]$SkipWindows,
    [switch]$SkipAndroid,
    [switch]$ApkOnly
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$release = Join-Path $root 'release'
New-Item -ItemType Directory -Force -Path $release | Out-Null

$config = Get-Content (Join-Path $root 'src-tauri\tauri.conf.json') -Raw | ConvertFrom-Json
$version = $config.version
$versionCode = $config.bundle.android.versionCode
if (-not $versionCode) { throw "tauri.conf.json is missing bundle.android.versionCode" }
Write-Host "Building Shadow720 $version (versionCode $versionCode)" -ForegroundColor Cyan

if (-not $SkipWindows) {
    Write-Host "`n== Windows installers ==" -ForegroundColor Cyan
    Push-Location $root
    try {
        npm run tauri build
        if ($LASTEXITCODE -ne 0) { throw "tauri build failed with exit code $LASTEXITCODE" }
    } finally {
        Pop-Location
    }

    $bundle = Join-Path $root 'src-tauri\target\release\bundle'
    foreach ($pattern in @('nsis\*.exe', 'msi\*.msi')) {
        Get-ChildItem -Path (Join-Path $bundle $pattern) -ErrorAction SilentlyContinue | ForEach-Object {
            Copy-Item $_.FullName (Join-Path $release $_.Name) -Force
            Write-Host "  staged $($_.Name)"
        }
    }
}

if (-not $SkipAndroid) {
    Write-Host "`n== Android ==" -ForegroundColor Cyan

    $sdk = if ($env:ANDROID_HOME) { $env:ANDROID_HOME } else { "$env:LOCALAPPDATA\Android\Sdk" }
    $ndk = Get-ChildItem (Join-Path $sdk 'ndk') -Directory -ErrorAction SilentlyContinue |
        Sort-Object Name -Descending | Select-Object -First 1
    if (-not $ndk) { throw "No Android NDK found under $sdk\ndk" }

    $env:ANDROID_HOME = $sdk
    $env:NDK_HOME = $ndk.FullName
    $toolchain = Join-Path $ndk.FullName 'toolchains\llvm\prebuilt\windows-x86_64\bin'
    $env:PATH = "$toolchain;$env:PATH"
    $env:CC_aarch64_linux_android = Join-Path $toolchain 'clang.exe'
    $env:CFLAGS_aarch64_linux_android = '--target=aarch64-linux-android26'
    $env:AR_aarch64_linux_android = Join-Path $toolchain 'llvm-ar.exe'

    # The Tauri CLI normally writes the resolved config into the APK's assets.
    # Building through Gradle directly skips that, and the notification plugin
    # reads it at startup via PluginManager.loadConfig, so without this file the
    # app throws during launch and closes immediately.
    $assetDir = Join-Path $root 'src-tauri\gen\android\app\src\main\assets'
    New-Item -ItemType Directory -Force -Path $assetDir | Out-Null
    $config | ConvertTo-Json -Depth 32 -Compress |
        Set-Content -Path (Join-Path $assetDir 'tauri.conf.json') -NoNewline -Encoding utf8
    Write-Host "  staged assets/tauri.conf.json"

    # Gradle reads the version from this gitignored file, not from tauri.conf.json.
    # Writing it here is what keeps the shipped versionCode in step with the config
    # instead of drifting to whatever was last written by hand.
    $propertiesPath = Join-Path $root 'src-tauri\gen\android\app\tauri.properties'
    @(
        '// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.'
        "tauri.android.versionName=$version"
        "tauri.android.versionCode=$versionCode"
    ) | Set-Content -Path $propertiesPath -Encoding utf8
    Write-Host "  synced tauri.properties to $version / $versionCode"

    Push-Location (Join-Path $root 'src-tauri')
    try {
        # `custom-protocol` is what makes this a production build. Without it Tauri
        # compiles in dev mode, points the webview at build.devUrl, and leaves the
        # frontend out of the binary entirely.
        cargo build --release --target aarch64-linux-android --features custom-protocol
        if ($LASTEXITCODE -ne 0) { throw "cargo build failed with exit code $LASTEXITCODE" }

        # Gradle's rustBuild task re-invokes the Tauri CLI, which needs Developer
        # Mode for symlinks. Staging the .so first lets that task be skipped.
        $jni = 'gen\android\app\src\main\jniLibs\arm64-v8a'
        New-Item -ItemType Directory -Force -Path $jni | Out-Null
        Copy-Item 'target\aarch64-linux-android\release\libshadow720_lib.so' `
            (Join-Path $jni 'libshadow720_lib.so') -Force

        Push-Location 'gen\android'
        try {
            # Both artifacts are built on every release run. The .aab is what Play
            # accepts; the .apk is what a tester sideloads and what a user outside
            # Play installs. Producing only one of them has already meant shipping
            # a release with nothing installable for sideloaders.
            if ($ApkOnly) {
                .\gradlew.bat assembleArm64Release -x rustBuildArm64Release
                if ($LASTEXITCODE -ne 0) { throw "gradle failed with exit code $LASTEXITCODE" }
            } else {
                .\gradlew.bat bundleArm64Release assembleArm64Release -x rustBuildArm64Release
                if ($LASTEXITCODE -ne 0) { throw "gradle failed with exit code $LASTEXITCODE" }
            }
        } finally {
            Pop-Location
        }
    } finally {
        Pop-Location
    }

    $apk = Join-Path $root 'src-tauri\gen\android\app\build\outputs\apk\arm64\release\app-arm64-release.apk'
    if (-not (Test-Path $apk)) { throw "Expected APK not found at $apk" }
    $apkTarget = Join-Path $release "Shadow720_${version}_arm64.apk"
    Copy-Item $apk $apkTarget -Force
    Write-Host "  staged $(Split-Path -Leaf $apkTarget)"

    if (-not $ApkOnly) {
        $aab = Join-Path $root 'src-tauri\gen\android\app\build\outputs\bundle\arm64Release\app-arm64-release.aab'
        if (-not (Test-Path $aab)) { throw "Expected AAB not found at $aab" }
        $aabTarget = Join-Path $release "Shadow720_${version}_arm64.aab"
        Copy-Item $aab $aabTarget -Force
        Write-Host "  staged $(Split-Path -Leaf $aabTarget)"
    }
}

Write-Host "`nArtifacts in $release" -ForegroundColor Green
Get-ChildItem $release | Select-Object Name, @{n = 'MB'; e = { [math]::Round($_.Length / 1MB, 1) } }
